export function normalizeLanguage(
  value: unknown,
  fallback: AppLanguage = "es",
): AppLanguage {
  if (typeof value !== "string") return fallback;
  const language = value.trim().toLowerCase().split(/[-_]/)[0];
  return language === "en" || language === "es" ? language : fallback;
}

function storedLanguage(): AppLanguage | null {
  try {
    const value = localStorage.getItem(LANGUAGE_STORAGE_KEY);
    return value === "es" || value === "en" ? value : null;
  } catch {
    return null;
  }
}

function browserLanguage(): AppLanguage {
  if (typeof navigator === "undefined") return "es";
  return normalizeLanguage(navigator.language, "es");
}

export function currentLanguage(): AppLanguage {
  return activeLanguage;
}

export function localeCode(language = activeLanguage) {
  return language === "en" ? "en-US" : "es-DO";
}

export function translateText(value: string, language = activeLanguage): string {
  if (language === "es" || !value) return value;
  const exact = english.get(value);
  if (exact) return exact;
  for (const [pattern, replacement] of englishPatterns) {
    if (pattern.test(value)) return value.replace(pattern, replacement);
  }
  return value;
}

function splitWhitespace(value: string) {
  const match = value.match(/^(\s*)(.*?)(\s*)$/s);
  return match
    ? {
        before: match[1] ?? "",
        content: match[2] ?? "",
        after: match[3] ?? "",
      }
    : { before: "", content: value, after: "" };
}

function shouldSkip(element: Element | null) {
  return Boolean(element?.closest(skippedContent));
}

function translateTextNode(node: Text) {
  if (shouldSkip(node.parentElement)) return;
  let state = textState.get(node);
  if (!state || node.data !== state.rendered) {
    state = { source: node.data, rendered: node.data };
    textState.set(node, state);
  }
  const { before, content, after } = splitWhitespace(state.source);
  const rendered = `${before}${translateText(content)}${after}`;
  state.rendered = rendered;
  if (node.data !== rendered) node.data = rendered;
}

function translateElementAttributes(element: Element) {
  if (shouldSkip(element)) return;
  let states = attributeState.get(element);
  if (!states) {
    states = new Map();
    attributeState.set(element, states);
  }
  for (const attribute of translatedAttributes) {
    const value = element.getAttribute(attribute);
    if (value === null) continue;
    let state = states.get(attribute);
    if (!state || value !== state.rendered) {
      state = { source: value, rendered: value };
      states.set(attribute, state);
    }
    const rendered = translateText(state.source);
    state.rendered = rendered;
    if (value !== rendered) element.setAttribute(attribute, rendered);
  }
}

function translateTree(root: Node) {
  if (root.nodeType === Node.TEXT_NODE) {
    translateTextNode(root as Text);
    return;
  }
  if (!(root instanceof Element) && !(root instanceof Document)) return;
  if (root instanceof Element) translateElementAttributes(root);
  const walker = document.createTreeWalker(
    root,
    NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT,
  );
  let node = walker.nextNode();
  while (node) {
    if (node.nodeType === Node.TEXT_NODE) translateTextNode(node as Text);
    else translateElementAttributes(node as Element);
    node = walker.nextNode();
  }
}

function updateLanguageControls() {
  document
    .querySelectorAll<HTMLSelectElement>("[data-language-selector]")
    .forEach((control) => {
      if (control.value !== activeLanguage) control.value = activeLanguage;
    });
}

function updateDocumentMetadata() {
  if (new URLSearchParams(window.location.search).has("invitacion")) return;
  const metadata = publicPageMetadata(window.location.pathname, activeLanguage);
  document.title = metadata.title;
  document
    .querySelector<HTMLMetaElement>('meta[name="description"]')
    ?.setAttribute("content", metadata.description);
}

export function setLanguage(
  language: AppLanguage,
  options: { persist?: boolean; notify?: boolean } = {},
) {
  const normalized = normalizeLanguage(language);
  const changed = normalized !== activeLanguage;
  activeLanguage = normalized;
  document.documentElement.lang = normalized;
  updateDocumentMetadata();
  if (options.persist !== false) {
    try {
      localStorage.setItem(LANGUAGE_STORAGE_KEY, normalized);
    } catch {
      // El idioma seguirá activo durante esta visita aunque no haya almacenamiento.
    }
  }
  updateLanguageControls();
  if (document.body) translateTree(document.body);
  if (changed && options.notify !== false) {
    window.dispatchEvent(
      new CustomEvent(LANGUAGE_CHANGE_EVENT, {
        detail: { language: normalized },
      }),
    );
  }
}

export function useUserLanguage(language: unknown) {
  setLanguage(normalizeLanguage(language, activeLanguage), {
    persist: true,
    notify: false,
  });
}

export function languageSelectorMarkup(extraClass = "") {
  return `<label class="language-selector ${extraClass}" aria-label="Idioma">
    <span aria-hidden="true">◎</span>
    <select data-language-selector translate="no" aria-label="Language / Idioma">
      <option value="es" ${activeLanguage === "es" ? "selected" : ""}>ES · Español</option>
      <option value="en" ${activeLanguage === "en" ? "selected" : ""}>EN · English</option>
    </select>
  </label>`;
}

export function initializeI18n() {
  activeLanguage = storedLanguage() ?? browserLanguage();
  document.documentElement.lang = activeLanguage;
  updateDocumentMetadata();
  if (!controlsBound) {
    document.addEventListener("change", (event) => {
      const control = (event.target as HTMLElement).closest<HTMLSelectElement>(
        "[data-language-selector]",
      );
      if (control) setLanguage(normalizeLanguage(control.value));
    });
    controlsBound = true;
  }
  if (!observer) {
    observer = new MutationObserver((mutations) => {
      for (const mutation of mutations) {
        if (mutation.type === "characterData") translateTextNode(mutation.target as Text);
        if (mutation.type === "attributes") translateElementAttributes(mutation.target as Element);
        mutation.addedNodes.forEach(translateTree);
      }
      updateLanguageControls();
    });
    observer.observe(document.documentElement, {
      subtree: true,
      childList: true,
      characterData: true,
      attributes: true,
      attributeFilter: [...translatedAttributes],
    });
  }
  if (document.body) translateTree(document.body);
}
